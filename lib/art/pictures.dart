/// 색칠할 그림 하나.
///
/// [regions] 는 아래에서 위 순서로 쌓인다(뒤에 있는 것이 위). 탭하면 위쪽부터 검사해 처음 맞는 영역을 칠한다.
/// 첫 영역은 항상 배경(캔버스 전체)이라 어디를 눌러도 무언가 칠해진다.
/// [details] 는 칠하지 않는 선 장식(입, 수염 등).
class Picture {
  final String id;
  final int pack;
  final List<Path> regions;
  final List<Path> details;
  const Picture(this.id, this.pack, this.regions, [this.details = const []]);

  /// 좌표 [p] (1000x1000 기준)에 있는 가장 위 영역 번호.
  int regionAt(Offset p) {
    for (var i = regions.length - 1; i >= 0; i--) {
      if (regions[i].contains(p)) return i;
    }
    return 0;
  }
}

