/// 해의 빛줄기: 중심에서 뻗는 삼각형 (안쪽은 해 원에 가려진다).
Path _ray(int i) {
  final a = i * math.pi / 4;
  double px(double d, double off) => 500 + d * math.cos(a + off);
  double py(double d, double off) => 500 + d * math.sin(a + off);
  return poly([px(200, -0.22), py(200, -0.22), px(420, 0), py(420, 0), px(200, 0.22), py(200, 0.22)]);
}

/// 꽃잎: 꽃 중심 둘레에 60도 간격.
Path _petal(int i) {
  final a = i * math.pi / 3;
  return rotatedOval(500 + 150 * math.cos(a), 380 + 150 * math.sin(a), 110, 75, i * 60.0);
}
